/**
 * CLI Core Engine for Universal ATS Resume Builder
 * Provides programmatic resume generation, candidate packaging, and headless PDF export.
 */

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");
const { analyzeATS } = require("./ats-checker.js");
const { renderResume } = require("./templates.js");

const ROOT_DIR = path.resolve(__dirname, "..");
const DATA_DIR = path.join(ROOT_DIR, "data");

function getEmptyResume(name = "Candidate", jobTitle = "Professional") {
  return {
    title: `${name} - Resume`,
    template: "london",
    color: "#1a91f0",
    font: "'Inter', sans-serif",
    density: "density-normal",
    personal: {
      fullName: name,
      jobTitle: jobTitle,
      email: "",
      phone: "",
      location: "",
      website: "",
      linkedin: "",
      github: "",
      photo: ""
    },
    summary: "",
    experience: [],
    education: [],
    skills: { technical: [], soft: [] },
    projects: [],
    certifications: [],
    custom: { title: "Additional Info", items: [] }
  };
}

function loadActiveResume() {
  const jsonPath = path.join(DATA_DIR, "resume_data.json");
  if (fs.existsSync(jsonPath)) {
    try {
      return JSON.parse(fs.readFileSync(jsonPath, "utf-8"));
    } catch (e) {
      console.warn("Failed to parse existing resume_data.json, starting fresh.");
    }
  }
  return getEmptyResume();
}

function saveActiveResume(data, targetDataDir = DATA_DIR) {
  if (!fs.existsSync(targetDataDir)) {
    fs.mkdirSync(targetDataDir, { recursive: true });
  }
  const jsonPath = path.join(targetDataDir, "resume_data.json");
  const jsPath = path.join(targetDataDir, "resume_data.js");

  fs.writeFileSync(jsonPath, JSON.stringify(data, null, 2), "utf-8");
  fs.writeFileSync(jsPath, `/** Local Data Bridge generated by resume-cli */\nwindow.RESUME_DATA = ${JSON.stringify(data, null, 2)};\n`, "utf-8");
}

/**
 * Generate a complete candidate workspace in a new folder
 */
function generateCandidatePackage(options) {
  const candidateName = options.name || options.candidate || "Candidate";
  const defaultOutputDir = path.resolve(ROOT_DIR, "..", `${candidateName} resume`);
  const outputDir = options.outDir ? path.resolve(options.outDir) : defaultOutputDir;

  console.log(`[CLI] Generating resume workspace for: ${candidateName}`);
  console.log(`[CLI] Target Directory: ${outputDir}`);

  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  // Determine Resume Data
  let resumeData;
  if (options.input && fs.existsSync(options.input)) {
    const raw = fs.readFileSync(options.input, "utf-8");
    if (options.input.endsWith(".json")) {
      resumeData = JSON.parse(raw);
    } else {
      resumeData = parseStructuredText(raw, candidateName, options.title);
    }
  } else {
    resumeData = getEmptyResume(candidateName, options.title || "Software Engineer");
  }

  // Apply CLI overrides if provided
  if (options.name) resumeData.personal.fullName = options.name;
  if (options.title) resumeData.personal.jobTitle = options.title;
  if (options.email) resumeData.personal.email = options.email;
  if (options.phone) resumeData.personal.phone = options.phone;
  if (options.location) resumeData.personal.location = options.location;
  if (options.summary) resumeData.summary = options.summary;
  if (options.template) resumeData.template = options.template;
  if (options.color) resumeData.color = options.color;

  resumeData.title = `${resumeData.personal.fullName} - Resume`;

  // Write candidate data
  const candidateDataDir = path.join(outputDir, "data");
  saveActiveResume(resumeData, candidateDataDir);

  // Copy Assets (css, js, lib) to candidate folder for offline standalone usage
  const copyDir = (src, dest) => {
    if (!fs.existsSync(dest)) fs.mkdirSync(dest, { recursive: true });
    const entries = fs.readdirSync(src, { withFileTypes: true });
    for (const entry of entries) {
      const srcPath = path.join(src, entry.name);
      const destPath = path.join(dest, entry.name);
      if (entry.isDirectory()) {
        copyDir(srcPath, destPath);
      } else {
        fs.copyFileSync(srcPath, destPath);
      }
    }
  };

  copyDir(path.join(ROOT_DIR, "css"), path.join(outputDir, "css"));
  copyDir(path.join(ROOT_DIR, "js"), path.join(outputDir, "js"));
  copyDir(path.join(ROOT_DIR, "lib"), path.join(outputDir, "lib"));

  // Copy and adapt index.html -> resume.html
  const mainHtmlPath = path.join(ROOT_DIR, "index.html");
  let htmlContent = fs.readFileSync(mainHtmlPath, "utf-8");
  // Update document title in HTML
  htmlContent = htmlContent.replace(/<title>[^<]*<\/title>/, `<title>${resumeData.personal.fullName} · Resume</title>`);
  fs.writeFileSync(path.join(outputDir, "resume.html"), htmlContent, "utf-8");

  // Also update active resume in resume-builder so index.html shows it
  saveActiveResume(resumeData, DATA_DIR);

  console.log(`[SUCCESS] Candidate HTML created: ${path.join(outputDir, "resume.html")}`);

  // Headless PDF compilation if requested or enabled
  const pdfPath = path.join(outputDir, `${candidateName.replace(/[^a-zA-Z0-9_-]/g, "_")}_Resume.pdf`);
  tryExportHeadlessPDF(path.join(outputDir, "resume.html"), pdfPath);

  // ATS Evaluation
  const ats = analyzeATS(resumeData);
  console.log(`[ATS SCORE] ${ats.score}/100 (${ats.rating.toUpperCase()})`);

  return {
    outputDir,
    htmlPath: path.join(outputDir, "resume.html"),
    pdfPath: fs.existsSync(pdfPath) ? pdfPath : null,
    ats
  };
}

function tryExportHeadlessPDF(htmlPath, outPdfPath) {
  const bravePath = "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser";
  if (fs.existsSync(bravePath)) {
    try {
      console.log(`[CLI] Compiling A4 vector PDF using Brave Browser...`);
      execSync(
        `"${bravePath}" --headless --disable-gpu --run-all-compositor-stages-before-draw --print-to-pdf="${outPdfPath}" --no-pdf-header-footer "file://${htmlPath}" 2>/dev/null`,
        { timeout: 15000 }
      );
      if (fs.existsSync(outPdfPath)) {
        console.log(`[SUCCESS] A4 Vector PDF compiled: ${outPdfPath}`);
        return true;
      }
    } catch (e) {
      console.warn(`[NOTICE] Headless PDF compilation notice: ${e.message}`);
    }
  }
  return false;
}

function parseStructuredText(rawText, candidateName, defaultTitle) {
  const resume = getEmptyResume(candidateName, defaultTitle || "Engineer");
  const lines = rawText.split("\n");
  let currentSection = null;

  lines.forEach(line => {
    const trimmed = line.trim();
    if (!trimmed) return;

    if (/^(experience|work experience|employment)/i.test(trimmed)) {
      currentSection = "experience";
      return;
    }
    if (/^(education|academic)/i.test(trimmed)) {
      currentSection = "education";
      return;
    }
    if (/^(skills|technical skills)/i.test(trimmed)) {
      currentSection = "skills";
      return;
    }
    if (/^(summary|profile)/i.test(trimmed)) {
      currentSection = "summary";
      return;
    }

    if (currentSection === "summary") {
      resume.summary = (resume.summary ? resume.summary + " " : "") + trimmed;
    } else if (currentSection === "skills") {
      const skills = trimmed.replace(/^[-*•]\s*/, "").split(/[,|]/).map(s => s.trim()).filter(Boolean);
      resume.skills.technical.push(...skills);
    } else if (currentSection === "experience") {
      if (trimmed.startsWith("-") || trimmed.startsWith("*") || trimmed.startsWith("•")) {
        const bullet = trimmed.replace(/^[-*•]\s*/, "");
        if (resume.experience.length > 0) {
          resume.experience[resume.experience.length - 1].bullets.push(bullet);
        }
      } else {
        resume.experience.push({
          id: `exp_${Date.now()}_${resume.experience.length}`,
          title: trimmed,
          company: "",
          location: "",
          startDate: "",
          endDate: "",
          current: false,
          bullets: []
        });
      }
    }
  });

  return resume;
}

module.exports = {
  getEmptyResume,
  loadActiveResume,
  saveActiveResume,
  generateCandidatePackage,
  tryExportHeadlessPDF
};
